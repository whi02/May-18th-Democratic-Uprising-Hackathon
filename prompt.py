def get_prompt(profile: str = "") -> ChatPromptTemplate:
    """Build the main RAG prompt with the user's character profile baked in.

    The profile is substituted via ``str.replace`` (not LangChain template
    variable resolution) so that ``{context}`` and ``{input}`` remain real
    template variables for the chain to fill at invoke-time.
    """
    system = NARRATIVE_SYSTEM_PROMPT.replace(
        "{profile}", profile or "특별한 설정 없음"
    )
    return ChatPromptTemplate.from_messages(
        [
            ("system", system),
            MessagesPlaceholder(variable_name="chat_history"),
            ("human", "{input}"),
        ]
    )


def get_condense_prompt() -> ChatPromptTemplate:
    """Prompt that rewrites a follow-up question into a standalone retrieval query."""
    return ChatPromptTemplate.from_messages(
        [
            ("system", CONDENSE_SYSTEM),
            MessagesPlaceholder(variable_name="chat_history"),
            ("human", "{input}"),
        ]
    )
