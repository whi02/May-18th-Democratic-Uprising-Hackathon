def _parse_input(raw_input: str) -> dict:
    """JSON 입력을 파싱한다. 실패하면 message만 있는 dict 반환."""
    try:
        return json.loads(raw_input)
    except (json.JSONDecodeError, TypeError):
        return {"message": raw_input}


def get_prompt(profile: str = "") -> ChatPromptTemplate:
    """메인 RAG 프롬프트 반환. profile은 {profile} 플레이스홀더에 정적으로 주입."""
    system = NARRATIVE_SYSTEM_PROMPT.replace(
        "{profile}", profile or "특별한 설정 없음"
    )
    return ChatPromptTemplate.from_messages([
        ("system", system),
        MessagesPlaceholder(variable_name="chat_history"),
        ("human", "{input}"),
    ])


def get_condense_prompt() -> ChatPromptTemplate:
    """히스토리 인식 retriever용 질문 재구성 프롬프트."""
